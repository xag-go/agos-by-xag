"""Write the contracts of `.importlinter` from scripts/layer_ratchet.py's rules.

Each contract's `ignore_imports` lists today's breaking importer -> imported pairs (as
found by layer_ratchet.scan()). import-linter treats an ignore that no longer matches
as an error, so after removing a break run this script and commit `.importlinter`.

    python scripts/importlinter_ignores.py          # rewrite .importlinter
    python scripts/importlinter_ignores.py --check  # fail when .importlinter is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import layer_ratchet as lr

CONFIG = lr.CORE / ".importlinter"
P = lr.ROOT
OTHER = [
    "api",
    "actions",
    "engine",
    "hermes_gateway",
    "db",
    "storage",
    "security",
    "background",
    "catalog",
    "shared",
]  # if packages
TOP = ["context", "config", "hook_relay", "migrate_root"]

HEADER = """\
; Layer rules for agos_core (import-linter: `uv run lint-imports` in services/core).
; Direct AND indirect import chains, module-level and lazy (inside functions).
; Today's breaks are listed under ignore_imports; an ignore that stops matching is an
; error, so the lists only shrink. GENERATED by scripts/importlinter_ignores.py from the
; rules in scripts/layer_ratchet.py, which also counts every statement (a second lazy
; import along an already ignored pair fails there).

[importlinter]
root_package = agos_core
include_external_packages = False
exclude_type_checking_imports = False
"""


def _section(key: str, name: str, body: list[str], pairs: list[str]) -> str:
    lines = [f"[importlinter:contract:{key}]", f"name = {name}", *body]
    if pairs:
        lines.append("ignore_imports =")
        lines += [f"    {pair}" for pair in pairs]
    return "\n".join(lines) + "\n"


def _list(key: str, modules: list[str]) -> list[str]:
    return [f"{key} =", *[f"    {m}" for m in modules]]


def render() -> str:
    counts, _ = lr.scan()
    known = lr._modules()
    pairs = {name: sorted(c) for name, c in counts.items()}
    top = [f"{P}.{m}" for m in TOP if f"{P}.{m}" in known]
    other = [m for m in OTHER if f"{P}.{m}" in known]
    texts = {c.name: c.text for c in lr.CONTRACTS}
    parts = [HEADER]
    parts.append(
        _section(
            "layers",
            texts["layers"],
            [
                "type = layers",
                "layers =",
                f"    {P}.api",
                f"    {P}.actions",
                "    " + " : ".join(f"{P}.{m}" for m in lr.SERVICE_INFRA),
                f"    {P}.db : {P}.storage : {P}.security",
                f"    {P}.domain",
            ],
            pairs["layers"],
        )
    )
    dto = [f"{P}.api.** -> {m}" for m in sorted(lr._DTO_MODULES)]
    parts.append(
        _section(
            "api-only-via-actions",
            texts["api-only-via-actions"],
            [
                "type = forbidden",
                f"source_modules = {P}.api",
                *_list(
                    "forbidden_modules",
                    [f"{P}.{m}" for m in ("engine", "hermes_gateway", "db", "storage", "security")],
                ),
                "allow_indirect_imports = True",
            ],
            dto + pairs["api-only-via-actions"],
        )
    )
    parts.append(
        _section(
            "core-not-plugin",
            texts["core-not-plugin"],
            [
                "type = forbidden",
                *_list("source_modules", [*[f"{P}.{m}" for m in [*other, "domain"]], *top]),
                f"forbidden_modules = {P}.hermes_plugin",
            ],
            pairs["core-not-plugin"],
        )
    )
    parts.append(
        _section(
            "plugin-standalone",
            texts["plugin-standalone"],
            [
                "type = forbidden",
                f"source_modules = {P}.hermes_plugin",
                *_list("forbidden_modules", [*[f"{P}.{m}" for m in [*other, "domain"]], *top]),
            ],
            pairs["plugin-standalone"],
        )
    )
    parts.append(
        _section(
            "domain-pure",
            texts["domain-pure"],
            [
                "type = forbidden",
                f"source_modules = {P}.domain",
                *_list(
                    "forbidden_modules", [*[f"{P}.{m}" for m in [*other, "hermes_plugin"]], *top]
                ),
            ],
            pairs["domain-pure"],
        )
    )
    parts.append(
        _section(
            "shared-pure",
            texts["shared-pure"],
            [
                "type = forbidden",
                f"source_modules = {P}.shared",
                *_list(
                    "forbidden_modules",
                    [
                        *[f"{P}.{m}" for m in [*other, "domain", "hermes_plugin"] if m != "shared"],
                        *top,
                    ],
                ),
            ],
            pairs["shared-pure"],
        )
    )
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if CONFIG.read_text(encoding="utf-8") != text:
            print(".importlinter is stale: run `python scripts/importlinter_ignores.py`")
            return 1
        return 0
    CONFIG.write_text(text, encoding="utf-8")
    print(f"wrote {CONFIG.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
